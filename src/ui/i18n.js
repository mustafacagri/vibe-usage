  const DEFAULT_LANGUAGE = 'en';
  let currentLanguage = DEFAULT_LANGUAGE;

  // Pure lookup for callers that hold their own language (main process, CLI).
  // Missing keys fall back to English, then to the key itself, never to an empty string.
  // Keys with CLDR plural variants (`key_one`, `key_few`, … `key_other`) resolve by `params.n`.
  // A language defines `_other` plus only the categories its grammar distinguishes.
  function isPlural(key) {
    return Object.prototype.hasOwnProperty.call(I18N[DEFAULT_LANGUAGE], `${key}_other`);
  }

  function pluralKey(language, table, key, n) {
    const variant = `${key}_${new Intl.PluralRules(language).select(n)}`;
    return Object.prototype.hasOwnProperty.call(table, variant) ? variant : `${key}_other`;
  }

  function translate(language, key, params = {}) {
    const resolvedLanguage = I18N[language] ? language : DEFAULT_LANGUAGE;
    const table = I18N[resolvedLanguage];
    const entry =
      isPlural(key) && typeof params.n === 'number'
        ? pluralKey(resolvedLanguage, table, key, params.n)
        : isPlural(key)
          ? `${key}_other`
          : key;
    let text = table[entry] ?? I18N[DEFAULT_LANGUAGE][entry] ?? key;
    for (const [name, value] of Object.entries(params)) {
      text = text.replaceAll(`{${name}}`, value);
    }
    return text;
  }

  function hasKey(key) {
    return Object.prototype.hasOwnProperty.call(I18N[DEFAULT_LANGUAGE], key) || isPlural(key);
  }

  function t(key, params) {
    return translate(currentLanguage, key, params);
  }

  function setLanguage(language) {
    if (I18N[language]) currentLanguage = language;
  }

  function getCurrentLanguage() {
    return currentLanguage;
  }

  const SUPPORTED_LANGUAGES = Object.freeze(Object.keys(I18N));

  const api = { I18N, SUPPORTED_LANGUAGES, DEFAULT_LANGUAGE, translate, hasKey, t, setLanguage, getCurrentLanguage };
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
  else root.VibeI18n = api;
