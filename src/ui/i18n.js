let currentLanguage = 'en';

function t(key, params = {}) {
  const langObj = I18N[currentLanguage] || I18N.en;
  let text = langObj[key] ?? I18N.en[key] ?? key;
  for (const [k, v] of Object.entries(params)) {
    text = text.replaceAll(`{${k}}`, v);
  }
  return text;
}

function setLanguage(lang) {
  if (I18N[lang]) {
    currentLanguage = lang;
  }
}

function getCurrentLanguage() {
  return currentLanguage;
}

function getSupportedLanguages() {
  return Object.entries(I18N).map(([code, obj]) => ({ code, name: obj.name }));
}

if (typeof module !== 'undefined' && module.exports) {
  module.exports = { I18N, t, setLanguage, getCurrentLanguage, getSupportedLanguages };
} else {
  window.VibeI18n = { I18N, t, setLanguage, getCurrentLanguage, getSupportedLanguages };
}
